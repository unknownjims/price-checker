#!/bin/bash
# 📱 Price Checker — Android Phone Installer
# Run this ENTIRE script in Termux on Amy's phone.
# It installs everything and starts the app on localhost:5010.
#
# Usage:
#   1. Copy this file to Amy's phone (USB, SD card, or download)
#   2. Open Termux
#   3. Run: bash /path/to/install-price-checker.sh
#
# This self-extracting script contains the entire app.
# No internet needed once copied.

set -e

# ─── Colors ───
GREEN='\033[0;32m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
NC='\033[0m'

echo -e "${BLUE}"
echo "╔══════════════════════════════════════════╗"
echo "║      Price Checker — Phone Setup        ║"
echo "║                                          ║"
echo "║  Works on your Android phone entirely    ║"
echo "║  offline. No server, no WiFi needed.     ║"
echo "╚══════════════════════════════════════════╝"
echo -e "${NC}"

# Step 1: Install dependencies
echo -e "${YELLOW}⏳ Installing Python and dependencies...${NC}"
pkg update -y 2>/dev/null | tail -1
pkg install python clang make libffi openssl -y 2>/dev/null | tail -1

# Step 2: Create app directory
APP_DIR="$HOME/price-checker"
mkdir -p "$APP_DIR"
cd "$APP_DIR"

# Step 3: Extract the app from the embedded tarball
echo -e "${YELLOW}⏳ Extracting app files...${NC}"
# Find and extract the base64 payload
PAYLOAD_LINE=$(grep -n "^# --- PAYLOAD BELOW ---" "$0" | cut -d: -f1)
PAYLOAD_LINE=$((PAYLOAD_LINE + 1))
tail -n +$PAYLOAD_LINE "$0" | base64 -d | tar xz

echo -e "${GREEN}✅ App files extracted${NC}"

# Step 4: Install Python packages
echo -e "${YELLOW}⏳ Installing Python packages (one-time)...${NC}"
pip install flask flask_sqlalchemy 2>&1 | tail -1
echo -e "${GREEN}✅ Python packages installed${NC}"

# Step 5: Create data directory
mkdir -p "$APP_DIR/data"

# Step 6: Start the server
echo ""
echo -e "${GREEN}========================================${NC}"
echo -e "${GREEN}✅ SETUP COMPLETE!${NC}"
echo -e "${GREEN}========================================${NC}"
echo ""
echo -e "${BLUE}📱 Starting Price Checker...${NC}"
echo ""
echo "  1. Open Chrome on this phone"
echo "  2. Go to: ${GREEN}http://localhost:5010${NC}"
echo "  3. Grant camera permission when asked"
echo "  4. Start scanning barcodes!"
echo ""
echo -e "${YELLOW}  📸 Camera scans barcodes automatically"
echo "  ✏️  Unknown item? Type the SKU once"
echo "  💾 Data stays on this phone permanently"
echo "  📤 Back up: menu → Settings → Export CSV${NC}"
echo ""
echo "  ⏭️  Next time, just run:  ${GREEN}cd ~/price-checker && python app.py${NC}"
echo "  (This installs once, runs forever)"
echo ""
echo "  Press Ctrl+C to stop the server"
echo ""

# Step 7: Run the server
cd "$APP_DIR"
python app.py

exit 0

